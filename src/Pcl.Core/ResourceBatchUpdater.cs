using System.Security.Cryptography;
using Newtonsoft.Json;

namespace Pcl.Core;
// 本地资源管理：扫描模组、光影和资源包，在文件变更前后校验依赖并保留事务恢复信息。
public sealed class PreparedResourceBatch : IDisposable
{
    internal string GameDirectory { get; }
    internal string StagingDirectory { get; }
    internal IReadOnlyDictionary<string, string> Before { get; }
    internal IReadOnlyDictionary<string, string> After { get; }
    internal bool Consumed { get; set; }
    public IReadOnlyList<string> Changes { get; }
    public IReadOnlyList<string> Warnings { get; }

    // [实现] PreparedResourceBatch 构造 的实现：执行 GameDirectory = gameDirectory；执行 StagingDirectory = staging；执行 Before = before。
    internal PreparedResourceBatch(
        string gameDirectory,
        string staging,
        IReadOnlyDictionary<string, string> before,
        IReadOnlyDictionary<string, string> after,
        IReadOnlyList<string> changes,
        IReadOnlyList<string> warnings
    )
    {
        GameDirectory = gameDirectory;
        StagingDirectory = staging;
        Before = before;
        After = after;
        Changes = changes;
        Warnings = warnings;
    }

    // [实现] Dispose 的实现：按 !Directory.Exists(StagingDirectory) 分支处理；执行 Directory.Delete(StagingDirectory, true)。
    public void Dispose()
    {
        if (!Directory.Exists(StagingDirectory))
            return;
        // This path is generated by PrepareAsync and never points at the live resource directories.
        Directory.Delete(StagingDirectory, true);
    }
}

/// <summary>Builds and validates the complete replacement set before touching the live instance.</summary>
public sealed class ResourceBatchUpdater(string gameDirectory, string loader, string gameVersion)
{
    private readonly string root = Path.GetFullPath(gameDirectory);
    private static readonly string[] ResourceDirectories = [
        "mods",
        "shaderpacks",
        "resourcepacks"
    ];
    // 覆盖文件影响依赖判断：必须随预览复制，并在提交前检查哈希；不能作为资源目录覆盖回去。
    private static readonly string[] ContextFiles = [
        "profile.json",
        "version.json",
        QuiltDependencyOverrides.RelativePath,
        FabricDependencyOverrides.RelativePath
    ];
    private const string Manifest = ".pcl-resources.json";
    // [实现] IsResource 的实现：计算并返回 relative == Manifest || ResourceDirectories.Any( x => relative.StartsWith(x + "/", StringCompar…。
    private static bool IsResource(string relative) => relative == Manifest || ResourceDirectories.Any(
        x => relative.StartsWith(x + "/", StringComparison.Ordinal)
    );
    // [实现] 功能：记录资源事务输入。实现：递归检查路径边界和符号链接，对资源及相关配置计算 SHA-256，并限制文件数和总体积。
    private static Dictionary<string, string> Snapshot(string directory, bool context = true)
    {
        var result = new Dictionary<string, string>(StringComparer.Ordinal);
        long bytes = 0;
        foreach (var name in ResourceDirectories)
        {
            // [实现] 对 ResourceDirectories 中的每一项：准备 var path = ResourceInstaller.SafeTarget(directory, name)；按 Directory.Exists(path) 分支处理。
            var path = ResourceInstaller.SafeTarget(directory, name);
            if (Directory.Exists(path))
                Walk(path);
        }

        foreach (var name in new[]
        {
            Manifest
        }.Concat(
            context
                ? ContextFiles
                : []
        ))
        {
            // [实现] 对 new[] { Manifest }.Concat( context ? ContextFiles : [] ) 中的每一项：准备 var path = ResourceInstaller.SafeTarget(directory, name)；按 File.Exists(path) 分支处理。
            var path = ResourceInstaller.SafeTarget(directory, name);
            if (File.Exists(path))
                Add(path);
        }

        return result;
        // [实现] Walk 的实现：遍历 Directory.EnumerateFileSystemEntries(path) 处理 item。
        void Walk(string path)
        {
            foreach (var item in Directory.EnumerateFileSystemEntries(path))
            {
                // [实现] 对 Directory.EnumerateFileSystemEntries(path) 中的每一项：执行 ResourceInstaller.SafeTarget( directory, Path.GetRelativePath(directory, item) )；按 Directory.Exists(item) 分支处理。
                ResourceInstaller.SafeTarget(
                    directory,
                    Path.GetRelativePath(directory, item)
                );
                if (Directory.Exists(item))
                    Walk(item);
                else
                    Add(item);
            }
        }

        // [实现] Add 的实现：准备 var input = File.OpenRead(path)；执行 bytes = checked(bytes + input.Length)；按 bytes > 8L * 1024 * 1024 * 1024 || result.Count >= 100_000 分支处理。
        void Add(string path)
        {
            using var input = File.OpenRead(path);
            bytes = checked(bytes + input.Length);
            if (bytes > 8L * 1024 * 1024 * 1024 || result.Count >= 100_000)
                throw new InvalidDataException("本次批量更新资源超过 8 GiB 或 100,000 文件，请分批处理。");
            result.Add(
                Path.GetRelativePath(directory, path)
                    .Replace('\\', '/'),
                Convert.ToHexString(
                    SHA256.HashData(input)
                )
                    .ToLowerInvariant()
            );
        }
    }

    // [实现] CheckSnapshot 的实现：按 expected.Count != current.Count || expected.Any( x => !current.TryGetValue(x.Key, out var value… 分支处理。
    private static void CheckSnapshot(
        IReadOnlyDictionary<string, string> expected,
        IReadOnlyDictionary<string, string> current,
        string message
    )
    {
        if (expected.Count != current.Count || expected.Any(
            x => !current.TryGetValue(x.Key, out var value) || value != x.Value
        ))
            throw new IOException(message);
    }

    // [实现] 功能：准备整批资源更新而不改动在线实例。实现：对资源、清单和 Quilt 覆盖配置做哈希快照，复制到暂存目录后统一安装并验证依赖；原实例库上下文只供读取。
    public async Task<PreparedResourceBatch> PrepareAsync(
        IEnumerable<LocalResourceUpdate> updates,
        ResourceCatalog catalog,
        DownloadService downloads,
        IProgress<InstallProgress>? progress = null,
        CancellationToken ct = default
    )
    {
        var selected = updates.ToArray();
        if (selected.Length == 0)
            throw new InvalidOperationException("请选择要批量更新的资源。");
        if (selected.Select(
            x => x.Current.Path
        )
            .Distinct(StringComparer.Ordinal)
            .Count() != selected.Length || selected.Select(
            x => x.Available.ProjectId
        )
            .Distinct(StringComparer.Ordinal)
            .Count() != selected.Length)
            throw new InvalidDataException("更新列表包含重复文件或项目。");
        using var lease = new FileStream(
            ResourceInstaller.SafeTarget(root, ".resources.lock"),
            FileMode.OpenOrCreate,
            FileAccess.ReadWrite,
            FileShare.None
        );
        var scan = new LocalResourceService(root, loader, gameVersion).Scan();
        foreach (var update in selected)
        {
            // [实现] 对 selected 中的每一项：准备 var current = scan.SingleOrDefault( x => x.Path == update.Current.Path && x.Sha1 == update.Curr…；按 current is null || current.Error is not null 分支处理；按 !current.Enabled 分支处理。
            var current = scan.SingleOrDefault(
                x => x.Path == update.Current.Path && x.Sha1 == update.Current.Sha1 && x.Size == update.Current.Size
            );
            if (current is null || current.Error is not null)
                throw new IOException("资源已被外部修改，请重新检查更新：" + update.Current.Name);
            if (!current.Enabled)
                throw new InvalidOperationException("批量更新前请启用资源：" + current.Name);
        }

        var before = Snapshot(root);
        var staging = ResourceInstaller.SafeTarget(
            root,
            ".pcl-resource-batches/" + Guid.NewGuid()
                .ToString("N")
        );
        Directory.CreateDirectory(staging);
        try
        {
            // [实现] 在异常保护范围内：遍历 before.Keys 处理 file；执行 CheckSnapshot( before, Snapshot(staging), "复制期间资源发生变化，批量更新未开始。" )；准备 var manifestPath = ResourceInstaller.SafeTarget(staging, Manifest)。
            foreach (var file in before.Keys)
            {
                // [实现] 对 before.Keys 中的每一项：执行 ct.ThrowIfCancellationRequested()；准备 var target = ResourceInstaller.SafeTarget(staging, file)；执行 Directory.CreateDirectory( Path.GetDirectoryName(target)! )。
                ct.ThrowIfCancellationRequested();
                var target = ResourceInstaller.SafeTarget(staging, file);
                Directory.CreateDirectory(
                    Path.GetDirectoryName(target)!
                );
                File.Copy(
                    ResourceInstaller.SafeTarget(root, file),
                    target
                );
            }

            CheckSnapshot(
                before,
                Snapshot(staging),
                "复制期间资源发生变化，批量更新未开始。"
            );
            var manifestPath = ResourceInstaller.SafeTarget(staging, Manifest);
            var managed = File.Exists(manifestPath)
                ? JsonConvert.DeserializeObject<List<ManagedResource>>(
                    File.ReadAllText(manifestPath)
                ) ?? []
                : [];
            foreach (var update in selected)
            {
                // [实现] 对 selected 中的每一项：准备 var current = update.Current；执行 managed.RemoveAll( x => x.Kind == current.Kind && x.FileName == Path.GetFileName(current.Path) …；执行 managed.Add( new( update.Available.ProjectId, "imported-" + current.Sha1, current.Name, current…。
                var current = update.Current;
                managed.RemoveAll(
                    x => x.Kind == current.Kind && x.FileName == Path.GetFileName(current.Path)
                );
                managed.Add(
                    new(
                        update.Available.ProjectId,
                        "imported-" + current.Sha1,
                        current.Name,
                        current.Version,
                        current.Kind,
                        Path.GetFileName(current.Path),
                        current.Sha1,
                        current.Size,
                        true,
                        DateTimeOffset.UtcNow,
                        []
                    )
                );
            }

            JsonFiles.Write(manifestPath, managed);
            foreach (var group in selected.GroupBy(
                x => x.Current.Kind
            ))
            {
                // 候选试装仅发生在隔离副本；安装器失败会回滚该副本，在线目录直到Apply才改变。
                // 使用统一表锁定全部用户选择的根版本，避免A先选最新版前置后误报B无解。
                var profile = new GameProfile(
                    "batch",
                    "batch",
                    gameVersion,
                    loader,
                    staging,
                    Path.Combine(staging, "version.json")
                );
                var plan = await ResourceDependencyPlanner.ResolveManyAsync(
                    catalog,
                    downloads,
                    group.Select(
                        x => x.Available
                    )
                        .ToArray(),
                    group.Key,
                    profile,
                    progress,
                    ct,
                    root
                );
                await new ResourceInstaller(staging, downloads, loader, gameVersion, root).InstallAsync(plan, progress, ct);
            }

            var warnings = new LocalResourceService(staging, loader, gameVersion, root).ValidateEnabledResources();
            if (loader is not ("fabric" or "quilt" or "forge" or "neoforge") && selected.Any(
                x => x.Current.Kind == ResourceKind.Mod
            ))
                warnings = warnings.Append("当前加载器没有完整本地约束分析器；仅核验平台版本与声明的项目依赖。")
                    .ToArray();
            var after = Snapshot(staging);
            CheckSnapshot(
                before,
                Snapshot(root),
                "下载期间资源被外部修改，批量更新未提交。"
            );
            var changes = selected.Select(
                x => $"{x.Current.Name}：{x.Current.Version} → {x.Available.Number}"
            )
                .Concat(
                    before.Keys.Union(after.Keys)
                        .Where(IsResource)
                        .Where(
                            x => x != Manifest && before.GetValueOrDefault(x) != after.GetValueOrDefault(x)
                        )
                        .Order(StringComparer.Ordinal)
                        .Select(
                            x => (before.ContainsKey(x)
                                ? after.ContainsKey(x)
                                    ? "替换："
                                    : "移除旧文件："
                                : "新增 / 前置：") + x
                        )
                )
                .ToArray();
            return new(root, staging, before, after, changes, warnings);
        }
        catch
        {
            // [实现] 捕获 空 后：执行 Directory.Delete(staging, true)；重新抛出当前异常。
            Directory.Delete(staging, true);
            throw;
        }
    }

    // [实现] 功能：提交已预览的整批更新。实现：再次核对在线与暂存快照，保留旧资源备份后移动新目录；异常时逆向恢复，避免覆盖用户在预览后的修改。
    public string Apply(PreparedResourceBatch prepared, CancellationToken ct = default)
    {
        if (prepared.GameDirectory != root || prepared.Consumed)
            throw new InvalidOperationException("更新预览已失效。");
        using var lease = new FileStream(
            ResourceInstaller.SafeTarget(root, ".resources.lock"),
            FileMode.OpenOrCreate,
            FileAccess.ReadWrite,
            FileShare.None
        );
        CheckSnapshot(
            prepared.Before,
            Snapshot(root),
            "预览后资源已被外部修改，未覆盖；请重新检查更新。"
        );
        CheckSnapshot(
            prepared.After,
            Snapshot(prepared.StagingDirectory),
            "暂存更新已发生变化，请重新下载。"
        );
        ct.ThrowIfCancellationRequested();
        var backup = ResourceInstaller.SafeTarget(
            root,
            ".pcl-backups/batch-" + Guid.NewGuid()
                .ToString("N")
        );
        Directory.CreateDirectory(backup);
        var old = new List<string>();
        var added = new List<string>();
        // [实现] Move 的实现：按 Directory.Exists(from) 分支处理。
        void Move(string from, string to)
        {
            if (Directory.Exists(from))
                Directory.Move(from, to);
            else
                File.Move(from, to);
        }

        try
        {
            // [实现] 在异常保护范围内：执行 JsonFiles.Write( Path.Combine(backup, "rollback.json"), new { state = "prepared", directories =…；遍历 ResourceDirectories.Append(Manifest) 处理 name；执行 CheckSnapshot( prepared.Before.Where( x => IsResource(x.Key) ) .ToDictionary(), Snapshot(backup…。
            JsonFiles.Write(
                Path.Combine(backup, "rollback.json"),
                new
                {
                    state = "prepared",
                    directories = ResourceDirectories,
                    manifest = Manifest,
                    hashes = prepared.Before.Where(
                        x => IsResource(x.Key)
                    )
                        .ToDictionary()
                }
            );
            foreach (var name in ResourceDirectories.Append(Manifest))
            {
                // [实现] 对 ResourceDirectories.Append(Manifest) 中的每一项：准备 var target = ResourceInstaller.SafeTarget(root, name)；按 !Directory.Exists(target) && !File.Exists(target) 分支处理；执行 Move( target, Path.Combine(backup, name) )。
                var target = ResourceInstaller.SafeTarget(root, name);
                if (!Directory.Exists(target) && !File.Exists(target))
                    continue;
                Move(
                    target,
                    Path.Combine(backup, name)
                );
                old.Add(name);
            }

            CheckSnapshot(
                prepared.Before.Where(
                    x => IsResource(x.Key)
                )
                    .ToDictionary(),
                Snapshot(backup, false),
                "提交前资源再次发生变化，已保留原文件并撤回。"
            );
            foreach (var name in ResourceDirectories.Append(Manifest))
            {
                // [实现] 对 ResourceDirectories.Append(Manifest) 中的每一项：准备 var source = ResourceInstaller.SafeTarget(prepared.StagingDirectory, name)；按 !Directory.Exists(source) && !File.Exists(source) 分支处理；执行 Move( source, ResourceInstaller.SafeTarget(root, name) )。
                var source = ResourceInstaller.SafeTarget(prepared.StagingDirectory, name);
                if (!Directory.Exists(source) && !File.Exists(source))
                    continue;
                Move(
                    source,
                    ResourceInstaller.SafeTarget(root, name)
                );
                added.Add(name);
            }

            JsonFiles.Write(
                Path.Combine(backup, "rollback.json"),
                new
                {
                    state = "committed",
                    directories = old,
                    manifest = Manifest,
                    hashes = prepared.Before.Where(
                        x => IsResource(x.Key)
                    )
                        .ToDictionary()
                }
            );
            prepared.Consumed = true;
            ResourceHistory.Record(root, "批量更新", prepared.Changes, backup);
            return backup;
        }
        catch
        {
            // Preserve even new files created externally during the commit rather than overwriting them on rollback.
            foreach (var name in added.AsEnumerable()
                .Reverse())
            {
                // [实现] 对 added.AsEnumerable() .Reverse() 中的每一项：准备 var target = ResourceInstaller.SafeTarget(root, name)；按 File.Exists(target) || Directory.Exists(target) 分支处理。
                var target = ResourceInstaller.SafeTarget(root, name);
                if (File.Exists(target) || Directory.Exists(target))
                    Move(
                        target,
                        Path.Combine(backup, "uncommitted-" + name)
                    );
            }

            foreach (var name in old.AsEnumerable()
                .Reverse())
            {
                // [实现] 对 old.AsEnumerable() .Reverse() 中的每一项：准备 var target = ResourceInstaller.SafeTarget(root, name)；按 File.Exists(target) || Directory.Exists(target) 分支处理；执行 Move( Path.Combine(backup, name), target )。
                var target = ResourceInstaller.SafeTarget(root, name);
                if (File.Exists(target) || Directory.Exists(target))
                    Move(
                        target,
                        Path.Combine(
                            backup,
                            "external-" + Guid.NewGuid()
                                .ToString("N") + "-" + name
                        )
                    );
                Move(
                    Path.Combine(backup, name),
                    target
                );
            }

            prepared.Consumed = true;
            throw;
        }
    }
}
